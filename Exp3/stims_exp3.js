// Make 12 fillers for one participant
function makeExp2Fillers() {
  // Safety Check
  // Current design: 6 lexical sets × 2 QP positions = 12 filler trials
  if (BASE_EXP2_FILLER.length !== 6) {
    throw new Error(
      `Exp2 filler design requires exactly 6 lexical sets, but ${BASE_EXP2_FILLER.length} were found.`
    );
  }
  // =========================================================
  // 1. Create OBJECT + SUBJECT version of every lexical set
  //
  // TOTAL:
  // 12 fillers
  // 6 object
  // 6 subject
  // =========================================================

  const trial_specs = [];

  BASE_EXP2_FILLER.forEach(
    set => {

      trial_specs.push({
        set: set,
        qp_position: "object"
      });

      trial_specs.push({
        set: set,
        qp_position: "subject"
      });

    }
  );


  // =========================================================
  // 2. Assign exactly 6 YES + 6 NO
  // =========================================================

  const response_conditions =
    jsPsych.randomization.shuffle([
      "yes",
      "yes",
      "yes",
      "yes",
      "yes",
      "yes",

      "no",
      "no",
      "no",
      "no",
      "no",
      "no"
    ]);


  trial_specs.forEach(
    (spec, i) => {

      spec.answer =
        response_conditions[i];

    }
  );


  // =========================================================
  // 3. Assign exactly 6 ES + 6 EF
  //
  // Also avoid perfect association between:
  //
  // ES ↔ YES
  // EF ↔ NO
  //
  // Each response category gets:
  // 3 ES + 3 EF
  // =========================================================

  const yes_indices = [];
  const no_indices = [];


  trial_specs.forEach(
    (spec, i) => {

      if (spec.answer === "yes") {

        yes_indices.push(i);

      } else {

        no_indices.push(i);

      }

    }
  );


  const yes_contexts =
    jsPsych.randomization.shuffle([
      "ES",
      "ES",
      "ES",
      "EF",
      "EF",
      "EF"
    ]);


  const no_contexts =
    jsPsych.randomization.shuffle([
      "ES",
      "ES",
      "ES",
      "EF",
      "EF",
      "EF"
    ]);


  yes_indices.forEach(
    (trial_index, i) => {

      trial_specs[
        trial_index
      ].context_condition =
        yes_contexts[i];

    }
  );


  no_indices.forEach(
    (trial_index, i) => {

      trial_specs[
        trial_index
      ].context_condition =
        no_contexts[i];

    }
  );


  // =========================================================
  // 4. Choose sentence forms
  //
  // Each lexical set occurs twice:
  // once OBJECT + once SUBJECT.
  //
  // If there are two sentence types,
  // use different sentence types across the two trials.
  // =========================================================

  BASE_EXP2_FILLER.forEach(
    set => {

      const set_specs =
        trial_specs.filter(
          spec =>
            spec.set === set
        );


      const options =
        jsPsych.randomization.shuffle(
          [...set.sentence_options]
        );


      // Object version
      set_specs[0]
        .sentence_option =
          options[0];


      // Subject version
      if (options.length > 1) {

        set_specs[1]
          .sentence_option =
            options[1];

      } else {

        set_specs[1]
          .sentence_option =
            options[0];

      }

    }
  );


  // =========================================================
  // 5. Convert specifications into actual filler trials
  // =========================================================

  const fillers =
    trial_specs.map(
      spec => {


        const set =
          spec.set;

        const qp_position =
          spec.qp_position;

        const context_condition =
          spec.context_condition;

        const answer =
          spec.answer;

        const sentence_option =
          spec.sentence_option;


        // =====================================================
        // Sentence
        // =====================================================

        const sentence =

          qp_position === "object"

            ? sentence_option
                .object_sentence

            : sentence_option
                .subject_sentence;


        // =====================================================
        // Context image
        // =====================================================

        let context_image;


        if (
          qp_position === "object" &&
          context_condition === "ES"
        ) {

          context_image =
            set.object_context_ES;

        }

        else if (
          qp_position === "object" &&
          context_condition === "EF"
        ) {

          context_image =
            set.object_context_EF;

        }

        else if (
          qp_position === "subject" &&
          context_condition === "ES"
        ) {

          context_image =
            set.subject_context_ES;

        }

        else {

          context_image =
            set.subject_context_EF;

        }


        // =====================================================
        // Critical image
        // =====================================================

        let critical_image;


        if (
          qp_position === "object" &&
          answer === "yes"
        ) {

          critical_image =
            set.object_critical_yes;

        }

        else if (
          qp_position === "object" &&
          answer === "no"
        ) {

          critical_image =
            set.object_critical_no;

        }

        else if (
          qp_position === "subject" &&
          answer === "yes"
        ) {

          critical_image =
            set.subject_critical_yes;

        }

        else {

          critical_image =
            set.subject_critical_no;

        }


        // =====================================================
        // Final filler trial
        // =====================================================

        return {

          id:
            `F${set.item}_` +
            `${qp_position.toUpperCase()}_` +
            `${context_condition}_` +
            `${answer.toUpperCase()}`,

          item:
            set.item,

          item_type:
            "filler",

          lexical_set:
            set.lexical_set,

          qp_position:
            qp_position,

          context_condition:
            context_condition,

          sentence_type:
            sentence_option.type,

          sentence:
            sentence,

          context_image:
            context_image,

          critical_image:
            critical_image,

          correct_response:
            answer === "yes"
              ? "예"
              : "아니오"

        };

      }
    );


  // =========================================================
  // 6. Randomize filler order
  // =========================================================

  return (
    jsPsych.randomization.shuffle(
      fillers
    )
  );

}